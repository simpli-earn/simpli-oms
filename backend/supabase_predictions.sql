-- Prediction-market paper trading tables. Safe to run more than once.
-- Run this once on the shared Supabase database as an admin (SQL editor). oms_app cannot create tables.
-- Requires supabase_schema.sql (the strategies table) to be applied first.

create table if not exists public.pm_accounts (
    strategy_id varchar(64) primary key references public.strategies(id),
    cash_budget numeric(24, 10) not null,
    cash numeric(24, 10) not null,
    cash_reserved numeric(24, 10) not null default 0,
    realized_pnl numeric(24, 10) not null default 0,
    fees_paid numeric(24, 10) not null default 0,
    created_at timestamptz not null default now()
);

create table if not exists public.pm_orders (
    id varchar(36) primary key,
    strategy_id varchar(64) not null references public.pm_accounts(strategy_id),
    client_order_id varchar(64),
    venue varchar(16) not null,
    market_id varchar(128) not null,
    title varchar(500) not null default '',
    outcome varchar(8) not null,
    action varchar(8) not null,
    type varchar(8) not null,
    count numeric(24, 10) not null,
    limit_price numeric(24, 10),
    status varchar(16) not null,
    filled_count numeric(24, 10) not null default 0,
    avg_price numeric(24, 10),
    fees numeric(24, 10) not null default 0,
    reserved numeric(24, 10) not null default 0,
    reject_reason varchar(500),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uq_pm_orders_strategy_client unique (strategy_id, client_order_id)
);

create index if not exists ix_pm_orders_strategy_id on public.pm_orders(strategy_id);
create index if not exists ix_pm_orders_market_id on public.pm_orders(market_id);
create index if not exists ix_pm_orders_status on public.pm_orders(status);

create table if not exists public.pm_fills (
    id bigint generated by default as identity primary key,
    order_id varchar(36) references public.pm_orders(id),
    strategy_id varchar(64) not null references public.pm_accounts(strategy_id),
    venue varchar(16) not null,
    market_id varchar(128) not null,
    outcome varchar(8) not null,
    action varchar(8) not null,
    count numeric(24, 10) not null,
    price numeric(24, 10) not null,
    fee numeric(24, 10) not null default 0,
    filled_at timestamptz not null default now()
);

create index if not exists ix_pm_fills_order_id on public.pm_fills(order_id);
create index if not exists ix_pm_fills_strategy_id on public.pm_fills(strategy_id);

create table if not exists public.pm_positions (
    id bigint generated by default as identity primary key,
    strategy_id varchar(64) not null references public.pm_accounts(strategy_id),
    venue varchar(16) not null,
    market_id varchar(128) not null,
    outcome varchar(8) not null,
    title varchar(500) not null default '',
    count numeric(24, 10) not null default 0,
    avg_price numeric(24, 10) not null default 0,
    realized_pnl numeric(24, 10) not null default 0,
    updated_at timestamptz not null default now(),
    constraint uq_pm_positions_key unique (strategy_id, venue, market_id, outcome)
);

create index if not exists ix_pm_positions_strategy_id on public.pm_positions(strategy_id);

alter table public.pm_accounts enable row level security;
alter table public.pm_orders enable row level security;
alter table public.pm_fills enable row level security;
alter table public.pm_positions enable row level security;

revoke all on table public.pm_accounts from public, anon, authenticated, service_role;
revoke all on table public.pm_orders from public, anon, authenticated, service_role;
revoke all on table public.pm_fills from public, anon, authenticated, service_role;
revoke all on table public.pm_positions from public, anon, authenticated, service_role;

do $$
declare
    tbl text;
    seq text;
begin
    if not exists (select 1 from pg_roles where rolname = 'oms_app') then
        return;
    end if;
    foreach tbl in array array['pm_accounts', 'pm_orders', 'pm_fills', 'pm_positions']
    loop
        execute format('grant select, insert, update on table public.%I to oms_app', tbl);
        execute format('drop policy if exists oms_app_access on public.%I', tbl);
        execute format(
            'create policy oms_app_access on public.%I for all to oms_app using (true) with check (true)',
            tbl
        );
    end loop;
    for seq in
        select pg_get_serial_sequence(format('public.%s', name), 'id')
        from (values ('pm_fills'), ('pm_positions')) as tables(name)
    loop
        if seq is not null then
            execute format('grant usage, select, update on sequence %s to oms_app', seq);
        end if;
    end loop;
end $$;
