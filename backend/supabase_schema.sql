-- OMS schema. Safe to run more than once on the shared Supabase database.
-- The backend connects as oms_app through the session pooler. Create that
-- role once before running this file if it does not exist yet:
--
--   create role oms_app login password 'choose-a-password';
--
-- This file does not change profiles, processing_jobs, or video_analyses.

create table if not exists public.strategies (
    id varchar(64) primary key,
    cash_budget numeric(24, 10) not null,
    cash_remaining numeric(24, 10) not null,
    cash_reserved numeric(24, 10) not null default 0,
    realized_pnl numeric(24, 10) not null default 0,
    created_at timestamptz not null default now()
);

alter table public.strategies
    alter column cash_budget type numeric(24, 10) using round(cash_budget::numeric, 10),
    alter column cash_remaining type numeric(24, 10) using round(cash_remaining::numeric, 10),
    alter column realized_pnl type numeric(24, 10) using round(realized_pnl::numeric, 10);

alter table public.strategies
    add column if not exists cash_reserved numeric(24, 10) not null default 0;

create table if not exists public.orders (
    id varchar(36) primary key,
    strategy_id varchar(64) not null references public.strategies(id),
    client_order_id varchar(48),
    alpaca_order_id varchar(64),
    asset_class varchar(16) not null,
    order_class varchar(16) not null,
    symbol varchar(32),
    side varchar(8),
    type varchar(16) not null,
    qty numeric(24, 10) not null,
    limit_price numeric(24, 10),
    stop_price numeric(24, 10),
    time_in_force varchar(8) not null,
    position_intent varchar(16),
    status varchar(32) not null default 'pending_new',
    filled_qty numeric(24, 10) not null default 0,
    filled_avg_price numeric(24, 10),
    applied_notional numeric(24, 10) not null default 0,
    reserved_notional numeric(24, 10) not null default 0,
    reject_reason varchar(500),
    request_payload jsonb not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint uq_orders_strategy_client unique (strategy_id, client_order_id)
);

alter table public.orders
    alter column qty type numeric(24, 10) using round(qty::numeric, 10),
    alter column limit_price type numeric(24, 10) using round(limit_price::numeric, 10),
    alter column stop_price type numeric(24, 10) using round(stop_price::numeric, 10),
    alter column filled_qty type numeric(24, 10) using round(filled_qty::numeric, 10),
    alter column filled_avg_price type numeric(24, 10) using round(filled_avg_price::numeric, 10),
    alter column applied_notional type numeric(24, 10) using round(applied_notional::numeric, 10);

alter table public.orders
    add column if not exists reserved_notional numeric(24, 10) not null default 0;

create index if not exists ix_orders_strategy_id on public.orders(strategy_id);
create index if not exists ix_orders_alpaca_order_id on public.orders(alpaca_order_id);
create index if not exists ix_orders_status on public.orders(status);

create table if not exists public.order_legs (
    id integer generated by default as identity primary key,
    order_id varchar(36) not null references public.orders(id) on delete cascade,
    symbol varchar(32) not null,
    ratio_qty numeric(24, 10) not null,
    side varchar(8) not null,
    position_intent varchar(16) not null,
    filled_qty numeric(24, 10) not null default 0,
    filled_avg_price numeric(24, 10),
    applied_notional numeric(24, 10) not null default 0
);

alter table public.order_legs
    alter column ratio_qty type numeric(24, 10) using round(ratio_qty::numeric, 10),
    alter column filled_qty type numeric(24, 10) using round(filled_qty::numeric, 10),
    alter column filled_avg_price type numeric(24, 10) using round(filled_avg_price::numeric, 10),
    alter column applied_notional type numeric(24, 10) using round(applied_notional::numeric, 10);

create index if not exists ix_order_legs_order_id on public.order_legs(order_id);

create table if not exists public.fills (
    id integer generated by default as identity primary key,
    order_id varchar(36) not null references public.orders(id),
    strategy_id varchar(64) not null references public.strategies(id),
    symbol varchar(32) not null,
    side varchar(8) not null,
    qty numeric(24, 10) not null,
    price numeric(24, 10) not null,
    filled_at timestamptz not null default now()
);

alter table public.fills
    alter column qty type numeric(24, 10) using round(qty::numeric, 10),
    alter column price type numeric(24, 10) using round(price::numeric, 10);

create index if not exists ix_fills_order_id on public.fills(order_id);
create index if not exists ix_fills_strategy_id on public.fills(strategy_id);
create index if not exists ix_fills_symbol on public.fills(symbol);

create table if not exists public.strategy_positions (
    id integer generated by default as identity primary key,
    strategy_id varchar(64) not null references public.strategies(id),
    symbol varchar(32) not null,
    asset_class varchar(16) not null,
    qty numeric(24, 10) not null default 0,
    avg_price numeric(24, 10) not null default 0,
    constraint uq_strategy_positions_strategy_symbol unique (strategy_id, symbol)
);

alter table public.strategy_positions
    alter column qty type numeric(24, 10) using round(qty::numeric, 10),
    alter column avg_price type numeric(24, 10) using round(avg_price::numeric, 10);

create index if not exists ix_strategy_positions_strategy_id
    on public.strategy_positions(strategy_id);
create index if not exists ix_strategy_positions_symbol
    on public.strategy_positions(symbol);

create table if not exists public.ledger_entries (
    id bigint generated by default as identity primary key,
    strategy_id varchar(64) not null references public.strategies(id),
    order_id varchar(36) references public.orders(id),
    symbol varchar(32),
    kind varchar(16) not null,
    cash_delta numeric(24, 10) not null default 0,
    qty_delta numeric(24, 10) not null default 0,
    price numeric(24, 10),
    created_at timestamptz not null default now()
);

alter table public.ledger_entries alter column cash_delta set default 0;
alter table public.ledger_entries alter column qty_delta set default 0;
alter table public.ledger_entries alter column created_at set default now();

create index if not exists ix_ledger_entries_strategy_id on public.ledger_entries(strategy_id);
create index if not exists ix_ledger_entries_order_id on public.ledger_entries(order_id);

-- Sum of cash_delta equals spendable cash. Sum of qty_delta for a symbol
-- equals that position. Skip strategies that already have ledger rows.
insert into public.ledger_entries (strategy_id, kind, cash_delta, qty_delta)
select s.id, 'opening', s.cash_remaining + s.cash_reserved, 0
from public.strategies s
where not exists (
    select 1 from public.ledger_entries e where e.strategy_id = s.id
);

insert into public.ledger_entries (strategy_id, symbol, kind, cash_delta, qty_delta, price)
select p.strategy_id, p.symbol, 'opening', 0, p.qty, p.avg_price
from public.strategy_positions p
where not exists (
    select 1
    from public.ledger_entries e
    where e.strategy_id = p.strategy_id and e.symbol = p.symbol
);

create table if not exists public.strategy_code (
    strategy_id varchar(64) primary key references public.strategies(id),
    revision integer not null default 0,
    schedule jsonb,
    updated_by varchar(128),
    updated_at timestamptz not null default now()
);

create table if not exists public.strategy_files (
    strategy_id varchar(64) not null references public.strategies(id),
    path varchar(512) not null,
    content bytea not null,
    sha256 varchar(64) not null,
    size integer not null,
    revision integer not null,
    updated_at timestamptz not null default now(),
    primary key (strategy_id, path)
);

alter table public.strategy_files drop column if exists deleted;

create table if not exists public.strategy_installs (
    strategy_id varchar(64) not null references public.strategies(id),
    host varchar(128) not null,
    installed boolean not null default true,
    version varchar(64),
    schedule jsonb,
    last_run_at timestamptz,
    last_run_status varchar(32),
    seen_at timestamptz not null default now(),
    primary key (strategy_id, host)
);

alter table public.strategies enable row level security;
alter table public.orders enable row level security;
alter table public.order_legs enable row level security;
alter table public.fills enable row level security;
alter table public.strategy_positions enable row level security;
alter table public.ledger_entries enable row level security;
alter table public.strategy_code enable row level security;
alter table public.strategy_files enable row level security;
alter table public.strategy_installs enable row level security;

revoke all on table public.strategies from public, anon, authenticated, service_role;
revoke all on table public.orders from public, anon, authenticated, service_role;
revoke all on table public.order_legs from public, anon, authenticated, service_role;
revoke all on table public.fills from public, anon, authenticated, service_role;
revoke all on table public.strategy_positions from public, anon, authenticated, service_role;
revoke all on table public.ledger_entries from public, anon, authenticated, service_role;
revoke all on table public.strategy_code from public, anon, authenticated, service_role;
revoke all on table public.strategy_files from public, anon, authenticated, service_role;
revoke all on table public.strategy_installs from public, anon, authenticated, service_role;

do $$
declare
    tbl text;
    seq text;
begin
    if not exists (select 1 from pg_roles where rolname = 'oms_app') then
        return;
    end if;
    execute 'grant usage on schema public to oms_app';
    execute 'grant connect on database postgres to oms_app';
    foreach tbl in array array[
        'strategies', 'orders', 'order_legs', 'fills', 'strategy_positions', 'ledger_entries',
        'strategy_code', 'strategy_files', 'strategy_installs'
    ]
    loop
        execute format('grant select, insert, update on table public.%I to oms_app', tbl);
        execute format('drop policy if exists oms_app_access on public.%I', tbl);
        execute format(
            'create policy oms_app_access on public.%I for all to oms_app using (true) with check (true)',
            tbl
        );
    end loop;
    -- Only the latest copy of each strategy file is kept, so removed files are deleted.
    execute 'grant delete on table public.strategy_files to oms_app';
    for seq in
        select pg_get_serial_sequence(format('public.%s', name), 'id')
        from (values ('order_legs'), ('fills'), ('strategy_positions'), ('ledger_entries')) as tables(name)
    loop
        if seq is not null then
            execute format('grant usage, select, update on sequence %s to oms_app', seq);
        end if;
    end loop;
end $$;
